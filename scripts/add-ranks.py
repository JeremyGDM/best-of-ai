DEFAULT_RANK = 5


def get_rank(slug):
    return RANKS.get(slug, DEFAULT_RANK)


def process_file(path):
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()

    m = re.match(r'^(---\n)(.*?)(---\n)', content, re.S)
    if not m:
        return False

    fm = m.group(2)
    slug_m = re.search(r"^slug:\s*'?([^'\n]+)'?", fm, re.M)
    if not slug_m:
        return False

    slug = slug_m.group(1).strip().strip("'")
    rank = get_rank(slug)

    # Remove existing rank line
    fm_lines = [l for l in fm.split('\n') if not l.startswith('rank:')]
    fm = '\n'.join(fm_lines)
    if not fm.endswith('\n'):
        fm += '\n'

    # Insert rank after 'featured:' line
    lines = fm.split('\n')
    new_lines = []
    inserted = False
    for line in lines:
        new_lines.append(line)
        if line.startswith('featured:') and not inserted:
            new_lines.append(f'rank: {rank}')
            inserted = True
    if not inserted:
        new_lines.append(f'rank: {rank}')

    new_fm = '\n'.join(new_lines)
    new_content = m.group(1) + new_fm + m.group(3) + content[m.end():]

    with open(path, 'w', encoding='utf-8') as f:
        f.write(new_content)
    return True


def main():
    files = sorted(f for f in os.listdir(TOOLS_DIR) if f.endswith('.md'))
    updated = 0
    rank_counts = {}
    for fname in files:
        slug = fname[:-3]
        rank = get_rank(slug)
        rank_counts[rank] = rank_counts.get(rank, 0) + 1
        path = os.path.join(TOOLS_DIR, fname)
        if process_file(path):
            updated += 1

    print(f'Updated {updated}/{len(files)} files.')
    print('Rank distribution:')
    for r in sorted(rank_counts, reverse=True):
        print(f'  Rank {r}: {rank_counts[r]} tools')


if __name__ == '__main__':
    main()
